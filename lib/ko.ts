export function ganzhiKo(gz: string): string {
  const stems = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
  return [...gz]
    .map((c) => {
      const s = stems.indexOf(c);
      if (s >= 0) return STEMS_KO[s];
      const b = BRANCHES_ZH.indexOf(c);
      if (b >= 0) return BRANCHES_KO[b];
      return c;
    })
    .join('');
}
